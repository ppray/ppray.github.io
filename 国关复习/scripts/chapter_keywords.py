def clean(raw: str) -> str:
    """去 SVG / HTML 标签 / markdown 符号 / 数字，只留中文连续串"""
    t = re.sub(r'<svg[\s\S]*?</svg>', ' ', raw, flags=re.I)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = re.sub(r'https?://\S+', ' ', t)
    t = re.sub(r'[#`\|\[\]\(\)（）]', ' ', t)
    t = re.sub(r'[0-9\.\-—～~%]+', ' ', t)
    return "".join(CJK.findall(t))


def clean_latin(raw: str) -> str:
    """保留 ASCII 字母与连字符，用于统计 SDR / CIPS / SWIFT 等缩写"""
    t = re.sub(r'<svg[\s\S]*?</svg>', ' ', raw, flags=re.I)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = re.sub(r'https?://\S+', ' ', t)
    return t


def lint():
    """词表自检：重复 key（须用 ast 解析源码，加载模块查不出）+ variant 子串重叠。

    统计口径是 sum(cn.count(v) for v in vs)，所以：
      - 同一 key 内的 variant 互含 → 该 key 虚高（必改）
      - 跨 key 的 variant 互含 → 短的那个虚高（概念不同可容忍，相同必改）
    另：清洗会剥掉连字符并拼接（"银行-主权"→"银行主权"），带连字符的 variant 恒为 0。
    """
    import ast
    tree = ast.parse(open(__file__, encoding='utf-8').read())
    node = next(n for n in tree.body
                if isinstance(n, ast.Assign) and getattr(n.targets[0], 'id', '') == 'DOMAIN')
    keys = [k.value for k in node.value.keys]
    dom = {k.value: [v.value for v in val.elts]
           for k, val in zip(node.value.keys, node.value.values)}

    # 1) 重复 key（dict 字面量后写覆盖先写，加载模块检测不到）
    dup = [k for k in set(keys) if keys.count(k) > 1]
    print("① 重复 key（后者静默覆盖前者，必改）:", dup or "无")

    # 2) variant 子串重叠
    items = list(dom.items())
    inner = [(k, a, b) for k, vs in items
             for i, a in enumerate(vs) for b in vs[i + 1:]
             if a and b and (a in b or b in a)]
    print("② 同一 key 内 variant 互含（虚高，必改）:")
    for x in inner or ["无"]:
        print("   ", x)
    bad_all = [(k1, a, k2, b) for i, (k1, v1) in enumerate(items) for k2, v2 in items[i + 1:]
               for a in v1 for b in v2 if a and b and (a in b or b in a)]
    # 短 variant 被长 variant 语境误计。a/b 谁短谁长不确定，须判向：
    #   a ⊂ b（a 短）→ 数 k1 前挖 b → 应有 EXCLUDE[k1] 含 b
    #   b ⊂ a（b 短）→ 数 k2 前挖 a → 应有 EXCLUDE[k2] 含 a
    def handled(x):
        k1, a, k2, b = x
        if a in b:
            return b in EXCLUDE.get(k1, [])
        return a in EXCLUDE.get(k2, [])
    bad = [x for x in bad_all if not handled(x)]
    done = [x for x in bad_all if handled(x)]
    print(f"③ 跨 key variant 互含（短者虚高，共 {len(bad_all)} 处，其中 {len(done)} 处已由 EXCLUDE 化解）:")
    for x in bad[:30]:
        print("   ", x)
    if bad:
        print("    ↑ 未化解的须加入 EXCLUDE（挖长短语保护短词）")

    # 3) 含非 CJK 字符的 variant（清洗后恒为 0，应移入 LATIN）
    non = [(k, v) for k, vs in items for v in vs
           if not re.fullmatch(r'[\u4e00-\u9fff]+', v)]
    print("④ 非纯中文 variant（计数恒为 0，应放 LATIN）:")
    for x in non or ["无"]:
        print("   ", x)


def count_key(cn: str, vs, excl) -> int:
    """朴素子串计数 + 负向排除：先把 EXCLUDE 长短语挖成等长占位符再数。

    EXCLUDE 挂在"被误计的短词 key"上，值为要挖掉的长短语。
    main 与 verify_card_counts 共用此函数，保证口径一致。
    """
    if excl:
        for e in excl:
            cn = cn.replace(e, "□" * len(e))
    return sum(cn.count(v) for v in vs)


