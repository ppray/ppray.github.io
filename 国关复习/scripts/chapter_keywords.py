CJK = re.compile(r'[\u4e00-\u9fff]{2,}')


def locate(src: str, arg: str):
    """按章节 id 定位行范围；返回 (start, end) 1-based 含首不含尾"""
    lines = open(src, encoding='utf-8').readlines()
    heads = [(i, l) for i, l in enumerate(lines, 1) if l.startswith('## ')]
    for idx, (ln, _) in enumerate(heads):
        if f'id="{arg}"' in heads[idx][1]:
            end = heads[idx + 1][0] if idx + 1 < len(heads) else len(lines)
            return ln, end
    raise SystemExit(f"未找到章节 id={arg}，可用：{[re.search(r'id=\"(.*?)\"', h).group(1) for _, h in heads]}")


