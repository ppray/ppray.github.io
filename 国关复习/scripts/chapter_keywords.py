def clean(raw: str) -> str:
    """去 SVG / HTML 标签 / markdown 符号 / 数字，只留中文连续串"""
    t = re.sub(r'<svg[\s\S]*?</svg>', ' ', raw, flags=re.I)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = re.sub(r'https?://\S+', ' ', t)
    t = re.sub(r'[#`\|\[\]\(\)（）]', ' ', t)
    t = re.sub(r'[0-9\.\-—～~%]+', ' ', t)
    return "".join(CJK.findall(t))


def clean_latin(raw: str) -> str:
    """保留 ASCII 字母与连字符，用于统计 SDR / CIPS / SWIFT 等缩写"""
    t = re.sub(r'<svg[\s\S]*?</svg>', ' ', raw, flags=re.I)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = re.sub(r'https?://\S+', ' ', t)
    return t


def main():
    src, a, b = sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None
    lines = open(src, encoding='utf-8').readlines()
    start, end = (locate(src, a) if b is None else (int(a), int(b)))
    raw = "".join(lines[start - 1:end - 1])
    cn = clean(raw)
    print(f"[语料] 行 {start}-{end} · 中文字符 {len(cn)}")

    print("\n" + "=" * 58 + "\n【一】领域术语词频\n" + "=" * 58)
    rows = sorted(((sum(cn.count(v) for v in vs), k) for k, vs in DOMAIN.items()),
                  reverse=True)
    rows = [r for r in rows if r[0]]

    lat = clean_latin(raw)
    lat_rows = sorted(((sum(lat.count(v) for v in vs), k)
                       for k, vs in LATIN.items()), reverse=True)
    lat_rows = [r for r in lat_rows if r[0]]

    for n, k in rows:
        print(f"{k:<22}{n:>4} 次  {'#' * min(n, 40)}")
    if lat_rows:
        print("-" * 34 + " 拉丁缩写（另计）")
        for n, k in lat_rows:
            print(f"{k:<22}{n:>4} 次  {'#' * min(n, 40)}")
    print(f"\n合计 {sum(n for n, _ in rows) + sum(n for n, _ in lat_rows)} 次 / "
          f"{len(rows) + len(lat_rows)} 个概念")

    print("\n" + "=" * 58 + "\n【二】jieba 高频词 TOP 40\n" + "=" * 58)
    words = [w for w in jieba.cut(cn) if len(w) >= 2 and w not in STOP and CJK.fullmatch(w)]
    for i, (w, n) in enumerate(Counter(words).most_common(40), 1):
        print(f"{i:>2}. {w:<10}{n:>4} 次")

    print("\n" + "=" * 58 + "\n【三】数字 / 时间锚点\n" + "=" * 58)
    flat = re.sub(r'<[^>]+>', ' ', raw)
    for name, p in {
        "年份节点": r'(?:1[6-9]|20)\d{2}\s*年(?:\s*\d{1,2}\s*月)?',
        "精确到日": r'(?:1[6-9]|20)\d{2}[.\-/]\d{1,2}[.\-/]\d{1,2}',
        # 后侧允许两位缩写年份（1973–74），否则漏抓
        "年代区间": r'(?:1[6-9]|20)\d{2}\s*(?:s|年代)?\s*[–\-~至]\s*(?:(?:1[6-9]|20)\d{2}(?:s|年代)?|\d{2})',
        "平价/比价": r'\d+(?:\.\d+)?\s*(?:美元|元)\s*/\s*(?:盎司|英镑|美元)',
        "万亿级规模": r'~?\d+(?:\.\d+)?\s*万亿(?:美元)?',
        "亿/万级规模": r'~?\d+(?:\.\d+)?\s*[亿万](?:美元|元|卢布)?',
        "分数/比值": r'\d+\s*/\s*\d+',
        "百分比/利差": r'~?\d+(?:\.\d+)?\s*(?:%|个百分点)',
    }.items():
        c = Counter(m.group(0).replace(' ', '') for m in re.finditer(p, flat))
        print(f"\n-- {name} --")
        for k, v in c.most_common(12):
            print(f"   {k:<18} x {v}")


if __name__ == '__main__':
    main()
